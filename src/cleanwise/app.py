"""Streamlit demo for dataset profiling and intervention-value recommendations."""
from __future__ import annotations
import sys
from pathlib import Path
import numpy as np
import pandas as pd
import streamlit as st
from sklearn.model_selection import train_test_split

from cleanwise.profiling import profile_dataset, infer_task
from cleanwise.interventions import SUPPORTED_INTERVENTIONS, apply_intervention
from cleanwise.experiment import make_meta_features, score_model
from cleanwise.meta_model import load_model, predict_interventions

st.set_page_config(page_title="CleanWise", page_icon="🧹", layout="wide")
st.title("🧹 CleanWise")
st.subheader("Predict the value of data-cleaning interventions")
st.write(
    "Upload a tabular CSV, choose the target, inspect data quality, and compare candidate "
    "interventions. Predictions are only available after training the meta-model on benchmark data."
)

uploaded = st.file_uploader("Upload a CSV file", type=["csv"])
if uploaded is None:
    st.info("Tip: begin with a small, public classification dataset. Do not upload sensitive data.")
    st.stop()

try:
    df = pd.read_csv(uploaded)
except Exception as exc:
    st.error(f"Could not read CSV: {exc}")
    st.stop()

if df.empty or len(df.columns) < 2:
    st.error("CSV must contain at least one feature column and one target column.")
    st.stop()

st.write(f"Dataset shape: **{df.shape[0]:,} rows × {df.shape[1]} columns**")
st.dataframe(df.head(10), use_container_width=True)
target = st.selectbox("Select target column", df.columns, index=len(df.columns)-1)
X = df.drop(columns=[target])
y = df[target]
if X.empty:
    st.error("Select a target while keeping at least one feature.")
    st.stop()

with st.expander("Dataset quality profile", expanded=True):
    profile = profile_dataset(X, y)
    left, right = st.columns(2)
    left.metric("Missing cells", f"{X.isna().sum().sum():,}")
    right.metric("Duplicate rows", f"{X.duplicated().sum():,}")
    st.json(profile)
    st.write("Missingness by column")
    missing = X.isna().mean().sort_values(ascending=False)
    st.bar_chart(missing)

model_path = Path("artifacts/cleanwise_meta_model.joblib")
if not model_path.exists():
    st.warning(
        "No trained meta-model found. Generate the benchmark and train it first; see README.md. "
        "Until then, you can run a direct comparison below, but it is not a meta-model prediction."
    )
    mode = "direct"
else:
    mode = st.radio("Recommendation mode", ["meta-model", "direct comparison"], horizontal=True)

corruption = st.selectbox("Known/suspected issue to investigate",
                          ["missingness", "outliers", "label_noise"])
level = st.slider("Expected corruption level (estimate)", 0.01, 0.40, 0.15, 0.01)
downstream_model = st.selectbox("Downstream classifier",
                                ["logistic_regression", "random_forest"])
candidates = st.multiselect("Candidate interventions", SUPPORTED_INTERVENTIONS,
                            default=SUPPORTED_INTERVENTIONS[:3])

if st.button("Rank interventions", type="primary"):
    if not candidates:
        st.error("Choose at least one intervention.")
        st.stop()
    try:
        infer_task(y)
        # Convert the target to stable string labels so mixed target types are handled consistently.
        y_model = y.astype(str)
        if y_model.isna().any():
            st.error("Target contains missing values. Remove or resolve them before continuing.")
            st.stop()
        if mode == "meta-model" and model_path.exists():
            bundle = load_model(model_path)
            records = []
            for action in candidates:
                feat = make_meta_features(X, y_model, corruption, level, action, downstream_model)
                records.append(feat)
            recommendation = predict_interventions(bundle, pd.DataFrame(records))
            st.success("Recommendations generated by the trained meta-model.")
            st.dataframe(recommendation, use_container_width=True)
            st.caption("These are estimates learned from the benchmark, not guaranteed improvements.")
        else:
            X_train, X_test, y_train, y_test = train_test_split(
                X, y_model, test_size=0.25, random_state=42, stratify=y_model
            )
            results = []
            # Corruption is not injected into user data automatically. This compares interventions
            # on the data as uploaded, with a fixed holdout and leakage-safe transforms.
            baseline = score_model(X_train, y_train, X_test, y_test, downstream_model, 42)
            for action in candidates:
                Xt, Xv = apply_intervention(X_train, X_test, action)
                scored = score_model(Xt, y_train, Xv, y_test, downstream_model, 42)
                results.append({
                    "intervention": action,
                    "macro_f1": scored["macro_f1"],
                    "delta_vs_baseline": scored["macro_f1"] - baseline["macro_f1"],
                    "runtime_seconds": scored["runtime_seconds"],
                })
            st.info("Direct comparison evaluates each candidate now; it is not a prediction of unseen intervention value.")
            st.dataframe(pd.DataFrame(results).sort_values("delta_vs_baseline", ascending=False),
                         use_container_width=True)
    except Exception as exc:
        st.error(f"Could not run recommendations: {exc}")
